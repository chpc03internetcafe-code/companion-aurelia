// Writes every row of the local embedded database (PGlite, cms/api/data/pglite) as one SQL file:
//   npm run db:sql:data       → cms/api/data/supabase-data.sql
// Paste it into Supabase → SQL Editor and run it after supabase-setup.sql, when this computer can't reach the
// database directly (e.g. an office network that blocks PostgreSQL ports). Typical use: `npm run db:seed` locally
// with DATABASE_URL empty and the SUPABASE_* storage keys set (so photos land in Supabase Storage), then this.
// Rows that already exist are skipped (ON CONFLICT DO NOTHING), and ID counters are moved past the copied rows.
// Stop the local API first: PGlite can't be opened by two processes at once.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

process.env.DATABASE_URL = ''; // always read the local database: .env never overrides a variable that is already set
const { q, closeDb, DATA_DIR } = await import('./index.js');

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(here, '../../data/supabase-data.sql');
const CHUNK = 200;
const ident = (s) => `"${s.replace(/"/g, '""')}"`;
const lit = (s) => `'${s.replace(/'/g, "''")}'`;

if (!fs.existsSync(DATA_DIR)) {
  console.error(`No local database at ${DATA_DIR}. Run npm run db:seed first (with DATABASE_URL empty).`);
  process.exit(1);
}

const tables = (await q(`SELECT c.relname AS name FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname = 'public' AND c.relkind = 'r' ORDER BY c.relname`)).map((r) => r.name);
const deps = await q(`SELECT cl.relname AS child, pr.relname AS parent FROM pg_constraint co
  JOIN pg_class cl ON cl.oid = co.conrelid JOIN pg_class pr ON pr.oid = co.confrelid
  JOIN pg_namespace n ON n.oid = cl.relnamespace
  WHERE co.contype = 'f' AND n.nspname = 'public' AND cl.relname <> pr.relname`);

// Parents before children, so foreign keys are satisfied (self-references load in the same statement).
const ordered = [];
const visiting = new Set();
const visit = (t) => {
  if (ordered.includes(t)) return;
  if (visiting.has(t)) throw new Error(`Circular foreign keys involving ${t}`);
  visiting.add(t);
  for (const d of deps) if (d.child === t) visit(d.parent);
  visiting.delete(t);
  ordered.push(t);
};
tables.forEach(visit);

const sql = [
  '-- Generated by `npm run db:sql:data` from the local database. Run in Supabase → SQL Editor after supabase-setup.sql.',
  '-- Existing rows are kept (ON CONFLICT DO NOTHING). Safe to run more than once.',
  'BEGIN;',
];
let total = 0;
for (const t of ordered) {
  const cols = (await q(`SELECT a.attname AS name, a.attidentity AS identity FROM pg_attribute a
    WHERE a.attrelid = $1::regclass AND a.attnum > 0 AND NOT a.attisdropped AND a.attgenerated = ''
    ORDER BY a.attnum`, [ident(t)]));
  const rows = (await q(`SELECT row_to_json(x)::text AS j FROM ${ident(t)} x`)).map((r) => r.j);
  if (!rows.length) continue;
  total += rows.length;
  const list = cols.map((c) => ident(c.name)).join(', ');
  sql.push(`-- ${t}: ${rows.length} rows`);
  for (let i = 0; i < rows.length; i += CHUNK) {
    const json = `[${rows.slice(i, i + CHUNK).join(',')}]`;
    if (json.includes('$aurelia$')) throw new Error(`Row data in ${t} contains the quoting tag $aurelia$`);
    sql.push(`INSERT INTO ${ident(t)} (${list}) SELECT ${list} FROM json_populate_recordset(NULL::${ident(t)}, $aurelia$${json}$aurelia$) ON CONFLICT DO NOTHING;`);
  }
  for (const c of cols.filter((c) => c.identity)) {
    sql.push(`SELECT setval(pg_get_serial_sequence(${lit(t)}, ${lit(c.name)}), COALESCE((SELECT MAX(${ident(c.name)}) FROM ${ident(t)}), 0) + 1, false);`);
  }
}
sql.push('COMMIT;', '');

fs.writeFileSync(out, sql.join('\n'));
await closeDb();
console.log(`✓ Wrote ${total} rows from ${ordered.length} tables to ${out} (${(fs.statSync(out).size / 1024).toFixed(0)} KB)`);
