// Writes the full database setup (schema + starter staff roles + default settings) as one SQL file:
//   npm run db:sql            → cms/api/supabase-setup.sql
// Paste it into Supabase → SQL Editor and run it when this computer can't reach the database directly
// (e.g. an office network that blocks PostgreSQL ports). Safe to run again, like `npm run db:init`.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { DEFAULT_ROLES } from '../lib/admin-auth.js';
import { defaultSettings } from '../services/settings.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(here, '../../supabase-setup.sql');
const lit = (v) => `'${String(v).replace(/'/g, "''")}'`;

const sql = [
  '-- Generated by `npm run db:sql`. Run in Supabase → SQL Editor. Safe to run more than once.',
  fs.readFileSync(path.join(here, 'schema.sql'), 'utf8'),
  '-- Starter staff roles',
  ...DEFAULT_ROLES.map((r) => `INSERT INTO admin_roles (name, description, permissions, is_system) VALUES (${lit(r.name)}, ${lit(r.description)}, ${lit(JSON.stringify(r.permissions))}, ${r.isSystem ? 'TRUE' : 'FALSE'}) ON CONFLICT (name) DO NOTHING;`),
  '-- Default site settings',
  ...Object.entries(defaultSettings).map(([k, v]) => `INSERT INTO site_settings (key, value) VALUES (${lit(k)}, ${lit(v)}) ON CONFLICT (key) DO NOTHING;`),
  '',
].join('\n');

fs.writeFileSync(out, sql);
console.log(`✓ Wrote ${out}`);
